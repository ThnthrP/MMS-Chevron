// ============================================================
// scripts/chevron/addMissingEmployeesFromPETracking.js
//
// Creates Employee records for people found in the PE tracking Excel
// who don't already exist in the system — a prerequisite step before
// running importMedicalExamRecords.js, so that a subsequent import
// pass can match 100% of rows instead of skipping unmatched names.
//
// IMPORTANT: Position (col F) and Division (col G) must match an
// EXISTING Position.name / Division.name EXACTLY (case-insensitive,
// trimmed). This script does NOT auto-create Position or Division —
// if a row references one that doesn't exist yet, that row is
// skipped and reported so you can either fix the Excel text or add
// the missing Position/Division first (via Manage Positions /
// Manage Departments) and re-run.
//
// col E (สถานที่ทำงานในพื้นที่เชฟรอน / Chevron Workplace, e.g.
// "Benchamas") is captured as free text into Employee.workplace —
// no lookup/validation against another table, unlike Position/Division.
// Requires schema.prisma to have Employee.workplace (see
// prisma/PATCH-schema-add-workplace.prisma) + a migration run first.
//
// empCode is auto-generated by continuing the numeric suffix after
// the highest existing "EXPT-###" code in the system.
//
// USAGE:
//   node scripts/chevron/addMissingEmployeesFromPETracking.js <path-to-xlsx> [options]
//
// OPTIONS:
//   --sheet="30-4-2026"   Worksheet name to read (default: first sheet)
//   --dry-run             Parse + match only, no writes. Always run
//                          this first to review what WOULD be created.
// ============================================================

import { PrismaClient } from "@prisma/client";
import ExcelJS from "exceljs";

const prisma = new PrismaClient();

const args = process.argv.slice(2);
const filePath = args.find((a) => !a.startsWith("--"));
const dryRun = args.includes("--dry-run");
const sheetArg = args.find((a) => a.startsWith("--sheet="));
const sheetName = sheetArg ? sheetArg.split("=")[1] : null;

if (!filePath) {
  console.error(
    'Usage: node scripts/chevron/addMissingEmployeesFromPETracking.js <path-to-xlsx> [--sheet="name"] [--dry-run]',
  );
  process.exit(1);
}

function cellText(cell) {
  const v = cell?.value;
  if (v === null || v === undefined) return null;
  if (typeof v === "object" && "result" in v)
    return String(v.result ?? "").trim() || null;
  if (typeof v === "object" && "richText" in v) {
    return (
      v.richText
        .map((r) => r.text)
        .join("")
        .trim() || null
    );
  }
  const s = String(v).trim();
  return s === "" ? null : s;
}

function cellDate(cell) {
  const v = cell?.value;
  if (v === null || v === undefined) return null;
  if (v instanceof Date) return v;
  if (typeof v === "object" && v.result instanceof Date) return v.result;
  const s = cellText(cell);
  if (!s) return null;
  const d = new Date(s);
  return isNaN(d.getTime()) ? null : d;
}

function normalizeName(s) {
  return (s || "").replace(/\s+/g, " ").trim().toLowerCase();
}

function normalizeNameNoSpace(s) {
  return (s || "").replace(/\s+/g, "").trim().toLowerCase();
}

// Rough heuristic to skip obviously junk rows (e.g. "New SSE" typed
// into the name column instead of an actual person) — a Thai name
// cell should contain at least one Thai-script character.
function looksLikeThaiName(s) {
  return !!s && /[\u0E00-\u0E7F]/.test(s);
}

async function main() {
  const workbook = new ExcelJS.Workbook();
  await workbook.xlsx.readFile(filePath);

  const worksheet = sheetName
    ? workbook.getWorksheet(sheetName)
    : workbook.worksheets[0];

  if (!worksheet) {
    console.error(
      `Worksheet ${sheetName ? `"${sheetName}"` : "(first sheet)"} not found in ${filePath}`,
    );
    process.exit(1);
  }

  console.log(`Reading sheet "${worksheet.name}" (${worksheet.rowCount} rows)`);
  if (dryRun) console.log("── DRY RUN — no database writes will be made ──\n");

  // ── preload existing employees for matching (same logic as the import script) ──
  const employees = await prisma.employee.findMany({
    select: {
      id: true,
      empCode: true,
      fullName: true,
      fullNameTH: true,
      fullNameEN: true,
    },
  });
  const byThaiName = new Map();
  const byThaiNameNoSpace = new Map();
  const byEnglishName = new Map();
  for (const e of employees) {
    if (e.fullNameTH) {
      byThaiName.set(normalizeName(e.fullNameTH), e);
      byThaiNameNoSpace.set(normalizeNameNoSpace(e.fullNameTH), e);
    }
    if (e.fullName) {
      byThaiName.set(normalizeName(e.fullName), e);
      byThaiNameNoSpace.set(normalizeNameNoSpace(e.fullName), e);
    }
    if (e.fullNameEN) byEnglishName.set(normalizeName(e.fullNameEN), e);
  }

  // ── preload Position / Division for exact-match lookup ──
  const positions = await prisma.position.findMany({
    select: { id: true, name: true },
  });
  const positionByName = new Map(
    positions.map((p) => [normalizeName(p.name), p]),
  );

  const divisions = await prisma.division.findMany({
    select: { id: true, name: true },
  });
  const divisionByName = new Map(
    divisions.map((d) => [normalizeName(d.name), d]),
  );

  // ── determine next empCode number (continues the "EXPT-###" sequence) ──
  let maxNum = 0;
  for (const e of employees) {
    const m = /^EXPT-(\d+)$/.exec(e.empCode || "");
    if (m) maxNum = Math.max(maxNum, parseInt(m[1], 10));
  }
  let nextNum = maxNum + 1;

  const toCreate = [];
  const skippedJunk = [];
  const skippedAlreadyExists = [];
  const skippedNoPosition = [];
  const skippedNoDivision = [];
  const errors = [];

  for (let rowNum = 2; rowNum <= worksheet.rowCount; rowNum++) {
    const row = worksheet.getRow(rowNum);
    const thaiName = cellText(row.getCell("A"));
    const engFirst = cellText(row.getCell("B"));
    const engLast = cellText(row.getCell("C"));

    if (!thaiName && !engFirst) continue; // empty row, silently skip

    if (!looksLikeThaiName(thaiName)) {
      skippedJunk.push({ row: rowNum, thaiName, engFirst, engLast });
      continue;
    }

    // ── already exists? skip ──
    let existing = null;
    if (thaiName) existing = byThaiName.get(normalizeName(thaiName)) || null;
    if (!existing && thaiName)
      existing = byThaiNameNoSpace.get(normalizeNameNoSpace(thaiName)) || null;
    if (!existing && engFirst) {
      const fullEN = normalizeName(`${engFirst} ${engLast || ""}`);
      existing = byEnglishName.get(fullEN) || null;
    }
    if (existing) {
      skippedAlreadyExists.push({
        row: rowNum,
        thaiName,
        matchedTo: existing.fullName,
      });
      continue;
    }

    try {
      const positionRaw = cellText(row.getCell("F"));
      const divisionRaw = cellText(row.getCell("G"));
      const birthDate = cellDate(row.getCell("H"));
      const workplace = cellText(row.getCell("E")); // ← NEW: col E, free text, no lookup

      const position = positionRaw
        ? positionByName.get(normalizeName(positionRaw)) || null
        : null;
      if (positionRaw && !position) {
        skippedNoPosition.push({ row: rowNum, thaiName, positionRaw });
        continue;
      }

      const division = divisionRaw
        ? divisionByName.get(normalizeName(divisionRaw)) || null
        : null;
      if (divisionRaw && !division) {
        skippedNoDivision.push({ row: rowNum, thaiName, divisionRaw });
        continue;
      }

      const empCode = `EXPT-${String(nextNum).padStart(3, "0")}`;
      nextNum++;

      const fullNameEN = [engFirst, engLast].filter(Boolean).join(" ") || null;

      toCreate.push({
        row: rowNum,
        empCode,
        fullName: fullNameEN || thaiName, // ← ใช้อังกฤษก่อน ถ้าไม่มีค่อย fallback ไทย
        fullNameTH: thaiName,
        fullNameEN,
        positionId: position?.id ?? null,
        division: division?.name ?? null,
        workplace, // ← NEW
        birthDate,
      });
    } catch (err) {
      errors.push({ row: rowNum, thaiName, error: err.message });
    }
  }

  // ── write (unless dry-run) ──
  let created = 0;
  if (!dryRun) {
    for (const c of toCreate) {
      await prisma.employee.create({
        data: {
          empCode: c.empCode,
          fullName: c.fullName,
          fullNameTH: c.fullNameTH,
          fullNameEN: c.fullNameEN,
          positionId: c.positionId,
          division: c.division,
          workplace: c.workplace, // ← NEW
          birthDate: c.birthDate,
          status: "active",
          availabilityStatus: "available",
          mobilizationStatus: "pending",
        },
      });
      created++;
    }
  }

  // ── summary ──
  console.log("\n── Summary ──");
  console.log(`To create:              ${toCreate.length}`);
  if (!dryRun) console.log(`Created:                ${created}`);
  console.log(`Already exists (skip):  ${skippedAlreadyExists.length}`);
  console.log(`Junk rows (skip):       ${skippedJunk.length}`);
  console.log(`Missing Position (skip): ${skippedNoPosition.length}`);
  console.log(`Missing Division (skip): ${skippedNoDivision.length}`);
  console.log(`Errors:                 ${errors.length}`);

  if (toCreate.length > 0) {
    console.log(
      `\n── ${dryRun ? "Would create" : "Created"} (${toCreate.length}) ──`,
    );
    for (const c of toCreate) {
      console.log(
        `  Row ${c.row}: ${c.empCode}  ${c.fullNameTH} (${c.fullNameEN || "—"})  position=${c.positionId ? "OK" : "—"}  division=${c.division || "—"}  workplace=${c.workplace || "—"}`,
      );
    }
  }

  if (skippedNoPosition.length > 0) {
    console.log(
      "\n── Skipped: Position not found in system (fix Excel or add Position first) ──",
    );
    for (const s of skippedNoPosition) {
      console.log(
        `  Row ${s.row}: "${s.thaiName}" → Position "${s.positionRaw}" not found`,
      );
    }
  }

  if (skippedNoDivision.length > 0) {
    console.log(
      "\n── Skipped: Division not found in system (fix Excel or add Division first) ──",
    );
    for (const s of skippedNoDivision) {
      console.log(
        `  Row ${s.row}: "${s.thaiName}" → Division "${s.divisionRaw}" not found`,
      );
    }
  }

  if (skippedJunk.length > 0) {
    console.log("\n── Skipped: junk rows (no Thai name detected) ──");
    for (const s of skippedJunk) {
      console.log(
        `  Row ${s.row}: TH="${s.thaiName || "—"}" EN="${s.engFirst || "—"} ${s.engLast || ""}"`,
      );
    }
  }

  if (errors.length > 0) {
    console.log("\n── Errors ──");
    for (const e of errors) {
      console.log(`  Row ${e.row} (${e.thaiName}): ${e.error}`);
    }
  }

  await prisma.$disconnect();
}

main().catch(async (err) => {
  console.error(err);
  await prisma.$disconnect();
  process.exit(1);
});
